// Helper query utilities
const getAllCrops = () => cropMasterCatalog;

const getCropById = (id) => cropMasterCatalog.find(c => c.id === id || c.id === id?.toLowerCase());

const getCropsByCategory = (category) => {
  if (!category || category === 'All') return cropMasterCatalog;
  return cropMasterCatalog.filter(c => c.category.toLowerCase() === category.toLowerCase());
};

const getCropsBySubCategory = (subCategory) => {
  if (!subCategory || subCategory === 'All') return cropMasterCatalog;
  return cropMasterCatalog.filter(c => c.subCategory && c.subCategory.toLowerCase() === subCategory.toLowerCase());
};

const getCategories = () => {
  const cats = new Set(cropMasterCatalog.map(c => c.category));
  return Array.from(cats);
};

const getSubCategories = (category) => {
  let list = cropMasterCatalog;
  if (category && category !== 'All') {
    list = list.filter(c => c.category.toLowerCase() === category.toLowerCase());
  }
  const subCats = new Set(list.map(c => c.subCategory).filter(Boolean));
  return Array.from(subCats);
};

const searchCrops = (query) => {
  if (!query || !query.trim()) return cropMasterCatalog;
  const q = query.toLowerCase().trim();
  return cropMasterCatalog.filter(c =>
    c.name.toLowerCase().includes(q) ||
    c.category.toLowerCase().includes(q) ||
    (c.subCategory && c.subCategory.toLowerCase().includes(q)) ||
    c.varieties.some(v => v.toLowerCase().includes(q)) ||
    c.states.some(s => s.toLowerCase().includes(q)) ||
    c.description.toLowerCase().includes(q)
  );
};

export default cropMasterCatalog;
export {
  getAllCrops,
  getCropById,
  getCropsByCategory,
  getCropsBySubCategory,
  getCategories,
  getSubCategories,
  searchCrops
};


